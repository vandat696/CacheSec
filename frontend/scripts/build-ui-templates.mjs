// Build the dependency-free browser bundle from readable, component-owned sources.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Script } from "node:vm";
import ts from "typescript";

const root = fileURLToPath(
  new URL("../design-reference/templates/", import.meta.url),
);
const manifest = JSON.parse(
  await readFile(resolve(root, "manifest.json"), "utf8"),
);
const printer = ts.createPrinter({ newLine: ts.NewLineKind.LineFeed });
const sources = new Set(manifest.sources);
const symbols = new Set();
const imports = [];
const chunks = [];

for (const source of manifest.sources) {
  const text = await readFile(resolve(root, source), "utf8");
  const file = ts.createSourceFile(
    source,
    text,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.JS,
  );
  if (file.parseDiagnostics.length)
    throw new Error(`Invalid template source: ${source}`);
  const statements = [];
  for (const statement of file.statements) {
    if (ts.isImportDeclaration(statement)) {
      const target = resolve(
        root,
        dirname(source),
        statement.moduleSpecifier.text,
      );
      const owner = [...sources].find((item) => resolve(root, item) === target);
      if (!owner) throw new Error(`Unknown template dependency in ${source}`);
      for (const binding of statement.importClause.namedBindings.elements) {
        if (binding.propertyName)
          throw new Error(`Aliased template import in ${source}`);
        imports.push(binding.name.text);
      }
      continue;
    }
    const names = ts.isVariableStatement(statement)
      ? statement.declarationList.declarations.map((item) => item.name.text)
      : [statement.name?.text];
    for (const name of names.filter(Boolean)) {
      if (symbols.has(name))
        throw new Error(`Duplicate template symbol: ${name}`);
      symbols.add(name);
    }
    statements.push(
      printer
        .printNode(ts.EmitHint.Unspecified, statement, file)
        .replace(/^export /, ""),
    );
  }
  chunks.push(`// Source: ${source}\n${statements.join("\n\n")}`);
}
for (const name of imports) {
  if (!symbols.has(name))
    throw new Error(`Missing template dependency: ${name}`);
}
const names = manifest.components.map((component) => component.name);
for (const name of names) {
  if (!symbols.has(name)) throw new Error(`Missing public template: ${name}`);
}
const bundle = `/* GENERATED by npm run templates:build. Edit templates/src/, not this bundle. */
(function (global) {
"use strict";
${chunks.join("\n\n")}

const components = { ${names.join(", ")} };
global.NoiUI = Object.freeze({
  ...components,
  create(name, options) {
    if (!components[name]) throw new Error('Unknown template: ' + name);
    return components[name](options);
  },
  version: ${JSON.stringify(manifest.version)},
});
})(window);
`;
new Script(bundle, { filename: "components.js" });
if (process.argv.includes("--check")) {
  if (
    (await readFile(resolve(root, manifest.script), "utf8")).replaceAll(
      "\r\n",
      "\n",
    ) !== bundle
  ) {
    throw new Error("Template bundle is stale. Run npm run templates:build.");
  }
  console.log(
    `Template bundle matches ${names.length} components and ${sources.size} source modules.`,
  );
} else {
  await writeFile(resolve(root, manifest.script), bundle);
  console.log(
    `Built ${names.length} templates without changing the NoiUI browser API.`,
  );
}
