"""Persistence port owned by local workspace operations, sharing the authority transaction."""

from typing import Protocol
from uuid import UUID

from app.identity.control_authority import RepositoryScope


class OperationRepository(Protocol):
    def now(self) -> float: ...
    def get(self, scope: RepositoryScope, identifier: UUID) -> dict | None: ...
    def add(self, scope: RepositoryScope, record: dict) -> None: ...
    def update(self, scope: RepositoryScope, record: dict) -> None: ...
    def pending(self, scope: RepositoryScope, worker: str | None = None) -> list[dict]: ...
