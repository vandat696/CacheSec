"""Real HTTP/DB/filesystem/Docker check on a disposable project; no model/provider calls.

Run on the trusted host: python tests/testing/manual_workspace_runtime.py PROFILE_JSON PRIVATE_ROOT
The synthetic human approves only this isolated test target (port 18001), never the dev app.
"""

import json
import secrets
import subprocess
import sys
import time
import urllib.error
import urllib.request
from pathlib import Path
from uuid import uuid4

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))

from app.artifacts.metadata_encoding import metadata_digest
from app.change_workflow.test_profiles import EDITABLE_PATH, OVERLAY_PATHS, load_test_profile
from app.testing.docker_commands import docker
from app.testing.docker_test_executor import DockerTestExecutor
from app.testing.test_worker import WorkerLock
from app.testing.worker_client import WorkerClient
from app.workspace_runtime.docker_runtime import runtime_configuration
from app.workspace_runtime.host_operations import HostWorkspaceOperations

CANDIDATE_SUFFIX = """
# Technical task candidate for an isolated implementation check, not generated by a model.
def validate_quotation(quotation, *, reference_date=None):
    import re
    if reference_date is None:
        raise ValueError("Trusted reference date required")
    raw = quotation.expires_on
    valid = False
    if type(raw) is str and re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", raw):
        try:
            valid = date.fromisoformat(raw) >= reference_date
        except ValueError:
            pass
    flags = () if valid else (
        QuotationFlag("expiration_review", "expires_on", "Cần xem xét ngày hết hạn"),
    )
    return QuotationValidation(
        quotation.id, flags, ("expiration_review",), "local-task-check-v1", reference_date
    )
"""

INITIALIZE = Path(__file__).with_name("workspace_fixture_provision.py").read_text(encoding="utf-8")


def main():
    profile = load_test_profile(Path(sys.argv[1]).resolve(strict=True))
    root = Path(sys.argv[2]).resolve()
    root.mkdir(parents=True, exist_ok=False)
    repository = Path(__file__).resolve().parents[3]
    source = root / "project"
    for path in OVERLAY_PATHS:
        target = source / path
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes((repository / path).read_bytes())
    baseline = (source / EDITABLE_PATH).read_bytes()
    config = root / "config"
    config.mkdir()
    store = root / "store"
    store.mkdir()
    workspace = root / "worker"
    workspace.mkdir()
    lock = WorkerLock(workspace)
    tenant, repo, principal, worker = (uuid4() for _ in range(4))
    identifier = uuid4().hex[:12]
    control_name = "cachesec-runtime-e2e-" + identifier
    network = "cachesec-runtime-e2e-" + identifier
    token, worker_key, app_operator, app_reader = (secrets.token_hex(32) for _ in range(4))
    configuration = {
        "tenant_id": str(tenant),
        "repo_id": str(repo),
        "repository_identity": "isolated-workspace-check",
        "root": "/source",
        "paths": list(OVERLAY_PATHS),
    }
    (config / "repository.json").write_text(json.dumps(configuration), encoding="utf-8")
    (config / "profile.json").write_text(json.dumps(profile.metadata()), encoding="utf-8")
    environment = config / "app.env"
    environment.write_text(
        "QUOTATION_DATABASE_URL=postgresql://workspace_e2e_runtime:isolated-test-only@db:5432/postgres\n"
        f"QUOTATION_FIXTURE_OPERATOR_TOKEN={app_operator}\nQUOTATION_FIXTURE_READER_TOKEN={app_reader}\n"
        "QUOTATION_REFERENCE_DATE=2026-11-07\n",
        encoding="utf-8",
    )
    runtime = {"network": network, "port": 18001, "environment_file": str(environment)}
    init = {
        "dsn": "postgresql://postgres:workspace-test-only@cachesec-workspace-check-db:5432/postgres",
        "token": token,
        "principal": str(principal),
        "config_digest": metadata_digest(runtime_configuration(runtime, profile)),
    }
    mounts = [
        "--mount",
        f"type=bind,source={config},target=/config,readonly",
        "--mount",
        f"type=bind,source={store},target=/store",
        "--mount",
        f"type=bind,source={source},target=/source,readonly",
    ]
    operation = None
    try:
        docker(
            [
                "network",
                "create",
                "--internal",
                "--label",
                "cachesec.task=workspace-runtime-e2e",
                network,
            ]
        )
        docker(["network", "connect", "--alias", "db", network, "cachesec-workspace-check-db"])
        # Initialization is trusted; its fixture token never enters a candidate container.
        initialized = subprocess.run(
            [
                "docker",
                "run",
                "-i",
                "--rm",
                "--network",
                "cachesec-workspace-check",
                *mounts,
                "cachesec-control-dev:local",
                "python",
                "-c",
                INITIALIZE,
            ],
            input=json.dumps(init).encode(),
            capture_output=True,
        )
        if initialized.returncode:
            print(initialized.stderr.decode("utf-8", errors="replace")[-2000:])
            raise RuntimeError("Isolated initialization failed")
        docker(
            [
                "run",
                "-d",
                "--name",
                control_name,
                "--label",
                "cachesec.task=workspace-runtime-e2e",
                "--network",
                "cachesec-workspace-check",
                "--publish",
                "127.0.0.1:18000:8000",
                *mounts,
                "--env",
                "DATABASE_URL=" + init["dsn"],
                "--env",
                "CONTROL_ARTIFACT_ROOT=/store",
                "--env",
                "CONTROL_REPOSITORY_CONFIG=/config/repository.json",
                "--env",
                "CONTROL_TEST_PROFILE_CONFIG=/config/profile.json",
                "--env",
                "CONTROL_TEST_WORKER_TOKEN=" + worker_key,
                "cachesec-control-dev:local",
            ]
        )
        opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))

        def request(path, body=None, credential=token, key=None, origin="http://127.0.0.1:18000"):
            req = urllib.request.Request(
                origin + path,
                data=json.dumps(body).encode() if body is not None else None,
                headers={
                    "Authorization": "Bearer " + credential,
                    "Content-Type": "application/json",
                    **({"Idempotency-Key": key} if key else {}),
                },
                method="POST" if path.endswith(("/snapshots", "/validate")) else None,
            )
            with opener.open(req, timeout=10) as response:
                return json.load(response)["data"]

        for _ in range(40):
            try:
                request("/api/v1/repository")
                break
            except OSError:
                time.sleep(0.25)
        snapshot = request("/api/v1/repository/snapshots")
        candidate = baseline.decode("utf-8") + CANDIDATE_SUFFIX
        revision = request(
            "/api/v1/changes/proposals",
            {"base_snapshot_id": snapshot["snapshot_id"], "content": candidate},
            key=str(uuid4()),
        )
        sources = WorkerClient("http://127.0.0.1:18000", worker_key, worker, "workspace-worker")
        host = HostWorkspaceOperations(sources, workspace, worker, source, runtime)
        write = request(
            "/api/v1/changes/workspace/source",
            {
                "proposal_id": revision["proposal_id"],
                "revision": revision["revision"],
                "artifact_digest": revision["artifact_digest"],
                "expected_snapshot_id": snapshot["snapshot_id"],
            },
            key=str(uuid4()),
        )
        assert host.execute_one()
        assert (source / EDITABLE_PATH).read_bytes() == candidate.encode()
        assert (
            request("/api/v1/changes/workspace/operations/" + write["id"])["status"] == "succeeded"
        )
        job = request(
            "/api/v1/changes/proposals/" + revision["proposal_id"] + "/tests",
            {"revision": 1},
            key=str(uuid4()),
        )
        tests = WorkerClient("http://127.0.0.1:18000", worker_key, worker)
        claimed = tests.post("claim")
        verdict = DockerTestExecutor(workspace, worker).execute(tests, claimed)
        tests.post(job["job_id"] + "/result", ticket=claimed["ticket"], result=verdict)
        assert verdict["outcome"] == "passed", verdict
        approval = request(
            "/api/v1/changes/workspace/approvals",
            {
                "proposal_id": revision["proposal_id"],
                "revision": 1,
                "artifact_digest": revision["artifact_digest"],
                "job_id": job["job_id"],
            },
            key=str(uuid4()),
        )
        operation = request(
            "/api/v1/changes/workspace/activations",
            {"approval_id": approval["id"], "expected_version": 0},
            key=str(uuid4()),
        )
        assert host.execute_one()
        observed = request("/api/v1/changes/workspace/operations/" + operation["id"])
        assert observed["status"] == "succeeded", observed
        for value, expected in [(None, True), ("2026-11-08", False)]:
            quotation = request(
                "/api/v1/quotations",
                {
                    "supplier_name": "Isolated live check",
                    "description": "real runtime",
                    "total_amount": "1",
                    "currency": "VND",
                    "expires_on": value,
                },
                app_operator,
                str(uuid4()),
                "http://127.0.0.1:18001",
            )
            flags = request(
                "/api/v1/quotations/" + quotation["id"] + "/validate",
                None,
                app_operator,
                origin="http://127.0.0.1:18001",
            )
            assert bool(flags["flags"]) == expected
        assert (
            request("/api/v1/changes/workspace/config")["active_artifact"]
            == revision["artifact_digest"]
        )
        report = {
            "source_write": "passed",
            "docker_checks": len(verdict["checks"]),
            "activation": "passed",
            "http_validation": "passed",
            "artifact_digest": revision["artifact_digest"],
            "model": "not_called",
        }
        (root / "result.json").write_text(json.dumps(report, indent=2), encoding="utf-8")
        print(json.dumps(report))
    finally:
        if operation:
            name = "cachesec-local-" + operation["id"].replace("-", "")
            for candidate_name in (name + "-gateway", name):
                info = subprocess.run(
                    ["docker", "container", "inspect", candidate_name], capture_output=True
                )
                if (
                    info.returncode == 0
                    and json.loads(info.stdout)[0]["Config"]["Labels"].get(
                        "cachesec.local-operation"
                    )
                    == operation["id"]
                ):
                    docker(["rm", "--force", candidate_name])
        info = subprocess.run(["docker", "container", "inspect", control_name], capture_output=True)
        if (
            info.returncode == 0
            and json.loads(info.stdout)[0]["Config"]["Labels"].get("cachesec.task")
            == "workspace-runtime-e2e"
        ):
            docker(["rm", "--force", control_name])
        subprocess.run(
            ["docker", "network", "disconnect", network, "cachesec-workspace-check-db"],
            capture_output=True,
        )
        info = subprocess.run(["docker", "network", "inspect", network], capture_output=True)
        if (
            info.returncode == 0
            and json.loads(info.stdout)[0]["Labels"].get("cachesec.task") == "workspace-runtime-e2e"
        ):
            docker(["network", "rm", network])
        lock.stream.close()


if __name__ == "__main__":
    main()
